import { writeFileSync } from 'node:fs';
import openapiTS, { astToString } from 'openapi-typescript';
import { buildOpenApiSpec } from '../openapi';

/** Regenerates packages/contracts (openapi.json + src/schema.ts). Run after changing route schemas. */
const out = new URL('../../../../packages/contracts/', import.meta.url);
const spec = await buildOpenApiSpec();
const json = `${JSON.stringify(spec, null, 2)}\n`;
writeFileSync(new URL('openapi.json', out), json);
const ast = await openapiTS(json, { exportType: true });
const header = '/**\n * GENERATED by `pnpm --filter @lawassist/api openapi` from the API route schemas. Do not edit.\n */\n\n';
writeFileSync(new URL('src/schema.ts', out), header + astToString(ast));
console.log('packages/contracts updated');
